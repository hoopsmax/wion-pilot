import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import type { FullConfig, Reporter, TestCase, TestResult } from '@playwright/test/reporter';
import { buildDraft, draftFileName, type DraftInput, type Evidence } from './draft.ts';
import { readFeatureLines, testAtLine, type BddTest } from './feature-lines.ts';
import { stepStatuses } from './step-status.ts';

/** The name of the attachment the test fixtures add with browser errors and failed requests. */
export const BROWSER_LOG_ATTACHMENT = 'wion-browser-log';

export interface BrowserLog {
  consoleErrors: string[];
  failedRequests: string[];
}

const EVIDENCE_LABELS: Record<string, string> = {
  screenshot: 'Screenshot',
  video: 'Video',
  trace: 'Trace',
};

interface BddSource {
  featureFile: string;
  scenario: BddTest | undefined;
  problem: string | undefined;
}

function browserLogOf(result: TestResult): BrowserLog | undefined {
  const attachment = result.attachments.find((a) => a.name === BROWSER_LOG_ATTACHMENT);
  return attachment?.body
    ? (JSON.parse(attachment.body.toString('utf8')) as BrowserLog)
    : undefined;
}

/**
 * Writes a bug-report draft (reports/bugs/*.md) for every test that failed unexpectedly. It never
 * stops the run: if it cannot write a draft, it says so loudly and the test result stays as it is.
 */
export default class BugReportReporter implements Reporter {
  #rootDir = process.cwd();
  #outDir = join(process.cwd(), 'reports', 'bugs');

  onBegin(config: FullConfig): void {
    // config.rootDir is the test folder (generated by playwright-bdd); the project folder is the
    // one holding playwright.config.ts.
    this.#rootDir = config.configFile ? dirname(config.configFile) : process.cwd();
    this.#outDir = join(this.#rootDir, 'reports', 'bugs');
    // Drafts from an earlier run would look like failures of this one.
    rmSync(this.#outDir, { recursive: true, force: true });
  }

  onTestEnd(test: TestCase, result: TestResult): void {
    if (result.status === test.expectedStatus) return;
    try {
      const input = this.#draftInput(test, result);
      const file = join(this.#outDir, draftFileName(input.featureFile, input.scenario));
      mkdirSync(this.#outDir, { recursive: true });
      writeFileSync(file, buildDraft(input), 'utf8');
      console.log(`Bug-report draft: ${relative(this.#rootDir, file)}`);
    } catch (error) {
      console.error(`Could not write a bug-report draft for "${test.title}":`, error);
    }
  }

  /** Reads the generated test file once: the .feature path and this scenario's step lines. */
  #bddSource(test: TestCase): BddSource {
    try {
      const lines = readFeatureLines(readFileSync(test.location.file, 'utf8'));
      const scenario = testAtLine(lines, test.location.line);
      return {
        featureFile: lines.featureFile,
        scenario,
        problem: scenario ? undefined : 'This test was not found in the generated BDD data.',
      };
    } catch (error) {
      return {
        featureFile: relative(this.#rootDir, test.location.file),
        scenario: undefined,
        problem: `The .feature lines could not be read: ${String(error)}`,
      };
    }
  }

  #draftInput(test: TestCase, result: TestResult): DraftInput {
    const notes: string[] = [];
    const source = this.#bddSource(test);
    if (source.problem) notes.push(`${source.problem} Steps are shown without .feature lines.`);

    const recorded = result.steps
      .filter((step) => step.category === 'test.step')
      .map((step) => ({ title: step.title, failed: step.error !== undefined }));
    const steps = source.scenario
      ? stepStatuses(source.scenario.steps, recorded)
      : recorded.map(
          (step) => ({ text: step.title, status: step.failed ? 'failed' : 'passed' }) as const,
        );
    if (!steps.some((step) => step.status === 'failed')) {
      notes.push(
        'No step failed by itself: the failure happened outside the steps (set-up, clean-up or a timeout).',
      );
    }

    const evidence: Evidence[] = result.attachments.flatMap((attachment) => {
      const label = EVIDENCE_LABELS[attachment.name];
      return label && attachment.path
        ? [{ label, path: relative(this.#outDir, attachment.path) }]
        : [];
    });
    const log = browserLogOf(result);
    const commit = process.env['GITHUB_SHA'];

    return {
      feature: test.titlePath()[3] ?? test.parent.title,
      scenario: test.title,
      featureFile: source.featureFile,
      featureFileLink: relative(this.#outDir, join(this.#rootDir, source.featureFile)),
      ...(source.scenario ? { scenarioLine: source.scenario.pickleLine } : {}),
      steps,
      errorMessage: result.error?.message ?? `The test ended as "${result.status}".`,
      when: result.startTime,
      browser: test.parent.project()?.name ?? 'unknown',
      ...(commit ? { commit } : {}),
      evidence,
      consoleErrors: log?.consoleErrors,
      failedRequests: log?.failedRequests,
      notes,
    };
  }
}
