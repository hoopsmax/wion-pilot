import { expectedAndActual, stripAnsi } from './expected-actual.ts';

export type StepStatus = 'passed' | 'failed' | 'not run';

export interface DraftStep {
  /** The Gherkin step with its keyword, for example "When Ava signs out". */
  text: string;
  status: StepStatus;
  /** The step's line in the .feature file, when known. */
  featureLine?: number;
}

export interface Evidence {
  label: string;
  /** A path relative to the draft file, so the link works where the draft is opened. */
  path: string;
}

export interface DraftInput {
  feature: string;
  scenario: string;
  /** Repository-relative .feature path, for example "tests/features/auth/auth.feature". */
  featureFile: string;
  /** From the draft file to the .feature file, for a clickable link. */
  featureFileLink: string;
  scenarioLine?: number;
  steps: DraftStep[];
  errorMessage: string;
  when: Date;
  browser: string;
  commit?: string;
  evidence: Evidence[];
  consoleErrors: string[];
  failedRequests: string[];
}

const NOT_DONE = 'DRAFT: verify before filing.';

function fence(text: string): string {
  return ['```text', text, '```'].join('\n');
}

function list(items: string[], whenEmpty: string): string {
  return items.length === 0 ? whenEmpty : items.map((item) => `- ${item}`).join('\n');
}

function stepLine(step: DraftStep, index: number): string {
  const number = `${String(index + 1)}.`;
  if (step.status === 'failed') return `${number} **${step.text} ❌ (fails here)**`;
  if (step.status === 'not run') return `${number} ${step.text} (not run)`;
  return `${number} ${step.text} ✅`;
}

function locationLine(input: DraftInput, failing: DraftStep | undefined): string {
  const scenarioAt = input.scenarioLine === undefined ? '' : `, line ${String(input.scenarioLine)}`;
  const failingAt =
    failing?.featureLine === undefined
      ? ''
      : ` (failing step: [line ${String(failing.featureLine)}](${input.featureFileLink}#L${String(failing.featureLine)}))`;
  return `**Feature file:** [${input.featureFile}](${input.featureFileLink})${scenarioAt}${failingAt}`;
}

function expectedActualSection(errorMessage: string): string {
  const found = expectedAndActual(errorMessage);
  if (found) {
    return ['## Expected', fence(found.expected), '', '## Actual', fence(found.actual)].join('\n');
  }
  // Never invent an expectation: say what is known and quote the error.
  const firstLine = stripAnsi(errorMessage).trim().split('\n')[0] ?? '';
  return [
    '## Expected',
    'The failing step passes.',
    '',
    '## Actual',
    fence(firstLine === '' ? '(no error message)' : firstLine),
  ].join('\n');
}

/** The Markdown of one bug-report draft. Pure, so it is easy to test and to reuse. */
export function buildDraft(input: DraftInput): string {
  const failing = input.steps.find((step) => step.status === 'failed');
  const meta = [
    `**When:** ${input.when.toISOString().slice(0, 16).replace('T', ' ')} UTC`,
    `**Browser:** ${input.browser}`,
    ...(input.commit ? [`**Commit:** ${input.commit.slice(0, 7)}`] : []),
  ].join(' · ');
  const evidence = input.evidence.map((item) => `[${item.label}](${item.path})`);
  const trace = input.evidence.find((item) => item.label === 'Trace');

  return [
    `> **${NOT_DONE}** Generated by Wion-Pilot from a failing test.`,
    '',
    `# ${input.feature}: ${input.scenario}`,
    '',
    locationLine(input, failing),
    meta,
    '',
    '## Steps to reproduce',
    input.steps.map(stepLine).join('\n'),
    '',
    expectedActualSection(input.errorMessage),
    '',
    '## Evidence',
    list(evidence, 'No screenshot, video or trace was kept for this test.'),
    ...(trace ? ['', `Open the trace with: \`npx playwright show-trace ${trace.path}\``] : []),
    '',
    '## Browser console errors',
    list(input.consoleErrors, 'None.'),
    '',
    '## Failed network requests',
    list(input.failedRequests, 'None.'),
    '',
    '## Full error',
    fence(stripAnsi(input.errorMessage).trim()),
    '',
  ].join('\n');
}

/** A readable, filesystem-safe name: "<feature file>--<scenario>.md". */
export function draftFileName(featureFile: string, scenario: string): string {
  const slug = (text: string) =>
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 80);
  const feature =
    featureFile
      .split('/')
      .pop()
      ?.replace(/\.feature$/, '') ?? 'feature';
  return `${slug(feature)}--${slug(scenario)}.md`;
}
